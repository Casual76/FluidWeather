/*
 * Le parole di `engine-ai-ui`, nelle due lingue dell'app. I default dell'engine sono italiani: lasciarne
 * uno solo e' una frase italiana in mezzo a una pagina inglese, quindi qui si passano **tutte**.
 * Dove l'app aveva gia' le sue parole (le righe di stato, gli errori, i tre tutorial delle chiavi) si
 * riusano quelle; il resto sta in `aiui.xml`. Le funzioni `assistantStrings` e `aiSettingsStrings` sono
 * pure (prendono un lettore di risorse) per un motivo: `AiUiStringsTest` le chiama con un lettore finto
 * e verifica che nessun campo resti al suo default italiano, anche quando l'engine ne aggiunge uno nuovo.
 * Il file e' stato scritto a partire dai campi delle due classi dell'engine 3.0.1.
 */

/** Le parole dell'overlay, della card e dei dettagli di un errore. */
@Composable
fun rememberAssistantStrings(): FluidAssistantStrings {
  val context = LocalContext.current
  val configuration = context.resources.configuration
  return remember(configuration) { assistantStrings(context.resources::getString) }
}

/** Le parole delle impostazioni dell'assistente (chiavi, ordine, modelli, preferenze, ultime richieste, diagnostica). */
@Composable
fun rememberAiSettingsStrings(): FluidAiSettingsStrings {
  val context = LocalContext.current
  val configuration = context.resources.configuration
  return remember(configuration) { aiSettingsStrings(context.resources::getString) }
}

